"""Write js/skins.js: which NS1 / NS2 skin rigs (js/sd/<id>_s1|_s2.js) and portraits (assets/icons) exist.

The game uses the NS1 skin for ★2 and the NS2 skin for ★3 (NS1 when a unit has no NS2).
Usage: python tools/sdbuild/skins_manifest.py   (after build_sd.py)
"""
import json
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
rigs, icons = {}, {}
for f in sorted(os.listdir(os.path.join(ROOT, "js", "sd"))):
    m = re.match(r"^([a-z0-9]+)_s([12])\.js$", f)
    if m:
        rigs.setdefault(m.group(1), []).append(int(m.group(2)))
for f in sorted(os.listdir(os.path.join(ROOT, "assets", "icons"))):
    m = re.match(r"^([a-z0-9]+)_s([12])\.webp$", f)
    if m:
        icons.setdefault(m.group(1), []).append(int(m.group(2)))
body = ("// generated by tools/sdbuild/skins_manifest.py: built skin rigs and portraits per unit (1 = NS1, 2 = NS2)\n"
        "(function (r) { const S = " + json.dumps({"rigs": rigs, "icons": icons}, separators=(",", ":")) +
        ";\n  if (typeof module !== 'undefined') module.exports = S; else r.SD_SKINS = S; })(this);\n")
open(os.path.join(ROOT, "js", "skins.js"), "w", encoding="utf-8").write(body)
print(len(rigs), "units with skin rigs,", sum(len(v) for v in rigs.values()), "rigs")
