// Reads js/sd/<id>.js rig data and writes js/clip_meta.js: { id: { clip: durationSeconds } }.
// The battle simulator needs clip lengths without loading the rigs (it also runs headless in node).
// Usage: node tools/build_clip_meta.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const dir = path.join(__dirname, '..', 'js', 'sd');
const out = {};
for (const f of fs.readdirSync(dir).sort()) {
  // units (<id>.js) and enemies (e_<Model>.js); skip atlas scripts (<id>.a50.js) and skins (<id>_s1.js)
  if (!/^(e_[A-Za-z0-9_]+|[a-z0-9]+)\.js$/.test(f)) continue;
  const id = f.slice(0, -3);
  const ctx = { window: {} };
  ctx.window = ctx; // the data scripts write window.SD_DATA and read SD_DATA bare
  vm.runInNewContext(fs.readFileSync(path.join(dir, f), 'utf8'), ctx);
  const d = ctx.SD_DATA && ctx.SD_DATA[id];
  if (!d || !d.clips) continue;
  out[id] = {};
  for (const [k, c] of Object.entries(d.clips)) out[id][k] = Math.round(c.dur * 1000) / 1000;
}
const body = '// generated by tools/build_clip_meta.js\n(function (r) { const M = ' + JSON.stringify(out) +
  ";\n  if (typeof module !== 'undefined') module.exports = M; else r.CLIP_META = M; })(this);\n";
fs.writeFileSync(path.join(__dirname, '..', 'js', 'clip_meta.js'), body);
console.log(Object.keys(out).length + ' rigs');
