def enemy_skill(u, key):
    """Active skill 1 / 2 (enemy files keep skills as a list; passives are skipped)."""
    import re
    acts = [x for x in (u.get("skills") or []) if isinstance(x, dict) and not x.get("passive")]
    i = int(key) - 1
    if i >= len(acts):
        return None
    s = acts[i]
    top = s.get("buff") or {}
    raw = re.sub(r"^[^>]*>", "", str(top.get("grid") or "0,0,0,0,1,0,0,0,0"))
    return {
        "rate": round(float(top.get("rate") or 0), 3),
        "range": int(top.get("range") or 1),
        "grid": [1 if x.strip() not in ("0", "") else 0 for x in raw.split(",")],
        "target": s.get("target", "enemy"),
        "pierce": bool(top.get("dismiss_guard")),
    }


def main():
    out = {}
    for rig, (eid, name, kind) in ENEMIES.items():
        u = F.get("korea/enemy/%s.yml" % eid, "enemy_%s.yml" % eid)
        st = u["stat"]
        out[rig] = {
            "eid": eid, "name": name, "kind": kind, "rarity": u.get("rarity", 2),
            "type": u.get("type", 0), "role": u.get("role", 1),
            "hp": st["hp"], "atk": st["atk"], "def": st["def"],  # [base, per level]
            "spd": st.get("spd", 4), "cri": st.get("cri", 0),
            "s1": enemy_skill(u, "1"), "s2": enemy_skill(u, "2"),
        }
        e = out[rig]
        print("%-18s %-20s %-6s %s %s hp%s atk%s def%s s1 %s" % (rig, eid, kind, "LHA"[e["type"]], "DAS"[e["role"]],
              e["hp"], e["atk"], e["def"], e["s1"] and (e["s1"]["rate"], e["s1"]["range"])))
    body = ("// generated by tools/fetch_lao_enemies.py from the original game data (lo.swaytwig.com, Korean server)\n"
            "(function (r) { const D = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) +
            ";\n  if (typeof module !== 'undefined') module.exports = D; else r.LAO_ENEMIES = D; })(this);\n")
    with open(os.path.join(ROOT, "js", "lao_enemies.js"), "w", encoding="utf-8") as f:
        f.write(body)
    print(len(out), "enemies -> js/lao_enemies.js")


if __name__ == "__main__":
    main()
